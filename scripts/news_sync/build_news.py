"""Rebuild content/home/news.md.

Sources:
  - https://hailab.io/news (fetched live)
  - scripts/news_sync/social_posts.json: Dakuo's own Twitter/LinkedIn posts, each condensed
    to one sentence: {"datetime": "YYYY-MM-DD", "label": "Mon YYYY", "md": "...",
    "links": [["Twitter"|"LinkedIn", url], ...]}. A post on both platforms is ONE entry with both links.
  - scripts/news_sync/lab_extra_links.json: {"<start of a lab news item>": [[name, url], ...]}
    to attach a social link to an existing lab item instead of duplicating it.

Usage (from repo root): python3 -I scripts/news_sync/build_news.py
"""
import html, json, os, re, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

def fetch_lab():
    req = urllib.request.Request('https://hailab.io/news/', headers={'User-Agent': 'Mozilla/5.0'})
    s = urllib.request.urlopen(req, timeout=30).read().decode('utf-8')
    s = s[s.find('<ol class="news-list"'):]
    s = s[:s.find('</ol>')]
    items = []
    for t, label, body in re.findall(r'<li><time datetime="([^"]*)">([^<]*)</time><div>(.*?)</div></li>', s, re.S):
        md = re.sub(r'<a [^>]*href="([^"]+)"[^>]*>(.*?)</a>',
                    lambda m: f"[{re.sub(r'<[^>]+>', '', m.group(2))}]({m.group(1)})", body, flags=re.S)
        md = re.sub(r'<(b|strong)>(.*?)</\1>', r'**\2**', md)
        md = html.unescape(re.sub(r'<[^>]+>', '', md))
        items.append(dict(datetime=t, label=label, md=' '.join(md.split())))
    if not items:
        raise SystemExit('No news items parsed from hailab.io; page structure may have changed.')
    return items

def to_html(md):
    t = html.escape(md, quote=False)
    t = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', r'<a href="\2" target="_blank" rel="noopener">\1</a>', t)
    return re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', t)

def main():
    lab = fetch_lab()
    soc = json.load(open(os.path.join(HERE, 'social_posts.json')))
    extra = json.load(open(os.path.join(HERE, 'lab_extra_links.json')))
    for i in lab:
        for k, v in extra.items():
            if i['md'].startswith(k):
                i['links'] = v
    # Month-only / year-only lab items sort after dated items in the same period.
    key = lambda i: (i['datetime'] + '-00-00')[:10]
    items = sorted(lab + soc, key=key, reverse=True)
    li = []
    for i in items:
        ls = i.get('links', [])
        tail = (' (' + ' · '.join(f'<a href="{u}" target="_blank" rel="noopener">{n}</a>' for n, u in ls) + ')') if ls else ''
        li.append(f'  <li><strong>{i["label"]}</strong> — {to_html(i["md"])}{tail}</li>')
    out = f'''---
# GENERATED by scripts/news_sync/build_news.py — edit social_posts.json / lab_extra_links.json, not this file.
# Recent news, synced from https://hailab.io/news plus one-line summaries of Dakuo's Twitter/LinkedIn posts.
widget: blank
widget_id: news
headless: true
active: true
weight: 30
title: Recent News
subtitle: ''
design:
  columns: '2'
---

<div class="news-scroll" style="max-height:480px; overflow-y:auto; padding-right:8px;">
<ul>
{chr(10).join(li)}
</ul>
</div>

<p style="margin-top:12px;">More: <a href="https://hailab.io/news" target="_blank" rel="noopener">lab news</a> · <a href="https://twitter.com/dakuowang" target="_blank" rel="noopener">Twitter</a> · <a href="https://www.linkedin.com/in/dakuowang/" target="_blank" rel="noopener">LinkedIn</a></p>
'''
    open(os.path.join(ROOT, 'content/home/news.md'), 'w').write(out)
    print(f'{len(items)} news items ({len(lab)} lab, {len(soc)} social)')

if __name__ == '__main__':
    main()
